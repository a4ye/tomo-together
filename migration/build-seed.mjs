// Turns the Atlas export in ht6-atlas-export/ into two D1 seed files.
//
//   node migration/build-seed.mjs
//
// Writes migration/out/seed-app.sql and migration/out/seed-custody.sql.
// Nothing is inferred: every field present in the export lands in a column, and
// build-seed refuses to run if a document carries a field the schema has no
// place for (so a schema drift is a hard failure, never a silent drop).
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readCollection, MongoDate, ObjectId } from './ejson.mjs';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const EXPORT_DIR = join(HERE, '..', '..', 'azure-to-cf-migration', 'ht6-atlas-export');
const OUT_DIR = join(HERE, 'out');

function lit(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new RangeError(`non-finite number ${value}`);
    return String(value);
  }
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (value instanceof MongoDate) return String(value.ms);
  if (value instanceof ObjectId) return `'${value.hex}'`;
  if (typeof value === 'string') return `'${value.replace(/'/g, "''")}'`;
  throw new TypeError(`cannot serialize ${Object.prototype.toString.call(value)}`);
}

function insert(table, columns, rows) {
  if (rows.length === 0) return [];
  return rows.map(
    (row) =>
      `INSERT INTO ${table} (${columns.join(', ')}) VALUES (${columns
        .map((c) => lit(row[c]))
        .join(', ')});`,
  );
}

/** Fail loudly if a document has a field this migration does not carry over. */
function assertFields(docs, allowed, what) {
  for (const doc of docs) {
    for (const key of Object.keys(doc)) {
      if (!allowed.includes(key)) {
        throw new Error(`${what}: unexpected field ${JSON.stringify(key)} in ${JSON.stringify(doc._id)}`);
      }
    }
  }
}

const jsonArray = (v) => JSON.stringify(v ?? []);

// ------------------------------------------------------------------ app db --

function buildApp() {
  const read = (name) => readCollection(join(EXPORT_DIR, `tomoyard__${name}.jsonl`));
  const appMeta = read('app_meta');
  const counters = read('counters');
  const users = read('users');
  const weights = read('weights');
  const friendships = read('friendships');
  const hangouts = read('hangouts');

  assertFields(appMeta, ['_id', 'value'], 'app_meta');
  assertFields(counters, ['_id', 'seq'], 'counters');
  assertFields(
    users,
    ['_id', 'username', 'name', 'birthday', 'pass_hash', 'salt', 'token', 'auth0_sub',
      'acorns', 'color', 'species', 'owned', 'equipped', 'interests', 'pos_x', 'pos_y', 'created_at'],
    'users',
  );
  assertFields(weights, ['_id', 'user_id', 'activity', 'weight'], 'weights');
  assertFields(
    friendships,
    ['_id', 'a_id', 'b_id', 'status', 'requested_by', 'vibe', 'created_at'],
    'friendships',
  );
  assertFields(
    hangouts,
    ['_id', 'creator_id', 'activity', 'activity_label', 'date', 'place', 'bonus_mult',
      'bonus_reason', 'photo', 'photo_by', 'completed_at', 'created_at', 'stake_units',
      'crypto_event_id', 'settled_at', 'member_ids', 'confirms', 'stakes', 'settlements',
      'nfc_tokens'],
    'hangouts',
  );

  const sql = ['-- generated by migration/build-seed.mjs; do not edit', 'PRAGMA defer_foreign_keys = TRUE;'];

  sql.push(...insert('app_meta', ['key', 'value'], appMeta.map((d) => ({ key: d._id, value: d.value }))));
  sql.push(...insert('counters', ['name', 'seq'], counters.map((d) => ({ name: d._id, seq: d.seq }))));

  sql.push(
    ...insert(
      'users',
      ['id', 'username', 'name', 'name_folded', 'birthday', 'pass_hash', 'salt', 'token', 'auth0_sub', 'acorns',
        'color', 'species', 'owned', 'equipped', 'interests', 'pos_x', 'pos_y', 'created_at'],
      users.map((u) => ({
        id: u._id,
        username: u.username,
        name: u.name,
        name_folded: String(u.name).toLowerCase(),
        birthday: u.birthday,
        pass_hash: u.pass_hash,
        salt: u.salt,
        token: u.token,
        auth0_sub: u.auth0_sub ?? null,
        acorns: u.acorns,
        color: u.color,
        species: u.species,
        owned: jsonArray(u.owned),
        equipped: jsonArray(u.equipped),
        interests: jsonArray(u.interests),
        pos_x: u.pos_x ?? null,
        pos_y: u.pos_y ?? null,
        created_at: u.created_at,
      })),
    ),
  );

  sql.push(
    ...insert(
      'weights',
      ['user_id', 'activity', 'weight', 'mongo_id'],
      weights.map((w) => ({
        user_id: w.user_id,
        activity: w.activity,
        weight: w.weight,
        mongo_id: w._id instanceof ObjectId ? w._id.hex : String(w._id),
      })),
    ),
  );

  sql.push(
    ...insert(
      'friendships',
      ['id', 'a_id', 'b_id', 'status', 'requested_by', 'vibe', 'created_at'],
      friendships.map((f) => ({
        id: f._id,
        a_id: f.a_id,
        b_id: f.b_id,
        status: f.status,
        requested_by: f.requested_by,
        vibe: f.vibe,
        created_at: f.created_at,
      })),
    ),
  );

  sql.push(
    ...insert(
      'hangouts',
      ['id', 'creator_id', 'activity', 'activity_label', 'date', 'place', 'bonus_mult',
        'bonus_reason', 'photo', 'photo_by', 'completed_at', 'created_at', 'stake_units',
        'crypto_event_id', 'settled_at'],
      hangouts.map((h) => ({
        id: h._id,
        creator_id: h.creator_id,
        activity: h.activity,
        activity_label: h.activity_label,
        date: h.date,
        place: h.place,
        bonus_mult: h.bonus_mult,
        bonus_reason: h.bonus_reason ?? null,
        photo: h.photo ?? null,
        photo_by: h.photo_by ?? null,
        completed_at: h.completed_at ?? null,
        created_at: h.created_at,
        stake_units: h.stake_units ?? null,
        crypto_event_id: h.crypto_event_id ?? null,
        settled_at: h.settled_at ?? null,
      })),
    ),
  );

  for (const h of hangouts) {
    sql.push(
      ...insert(
        'hangout_members',
        ['hangout_id', 'user_id', 'position'],
        (h.member_ids ?? []).map((user_id, position) => ({ hangout_id: h._id, user_id, position })),
      ),
    );
    sql.push(
      ...insert(
        'confirms',
        ['hangout_id', 'u1', 'u2', 'confirmed_at', 'position'],
        (h.confirms ?? []).map((c, position) => ({
          hangout_id: h._id, u1: c.u1, u2: c.u2, confirmed_at: c.confirmed_at, position,
        })),
      ),
    );
    sql.push(
      ...insert(
        'hangout_stakes',
        ['hangout_id', 'user_id', 'staked_at', 'position'],
        (h.stakes ?? []).map((s, position) => ({
          hangout_id: h._id, user_id: s.user_id, staked_at: s.staked_at, position,
        })),
      ),
    );
    sql.push(
      ...insert(
        'hangout_settlements',
        ['hangout_id', 'user_id', 'status', 'payout_units', 'position'],
        (h.settlements ?? []).map((s, position) => ({
          hangout_id: h._id, user_id: s.user_id, status: s.status, payout_units: s.payout_units, position,
        })),
      ),
    );
    sql.push(
      ...insert(
        'nfc_tokens',
        ['hangout_id', 'user_id', 'token', 'expires_at', 'position'],
        (h.nfc_tokens ?? []).map((t, position) => ({
          hangout_id: h._id, user_id: t.user_id, token: t.token, expires_at: t.expires_at, position,
        })),
      ),
    );
  }

  return {
    sql,
    counts: {
      app_meta: appMeta.length,
      counters: counters.length,
      users: users.length,
      weights: weights.length,
      friendships: friendships.length,
      hangouts: hangouts.length,
    },
  };
}

// -------------------------------------------------------------- custody db --

function buildCustody() {
  const read = (name) => readCollection(join(EXPORT_DIR, `ht6_crypto__${name}.jsonl`));
  const users = read('crypto_users');
  const events = read('crypto_events');
  const withdrawals = read('crypto_withdrawals');
  const idempotency = read('crypto_idempotency');

  assertFields(users, ['_id', 'externalUserId', 'balanceUnits', 'lastGrantPeriod', 'createdAt', 'updatedAt'], 'crypto_users');
  assertFields(events, ['_id', 'id', 'host', 'title', 'startsAt', 'stakeUnits', 'multiplierBps', 'status', 'rsvps', 'createdAt', 'revision', 'updatedAt'], 'crypto_events');
  assertFields(withdrawals, ['_id', 'id', 'externalUserId', 'transferId', 'amountUnits', 'destination', 'status', 'refunded', 'createdAt', 'updatedAt'], 'crypto_withdrawals');
  assertFields(idempotency, ['_id', 'externalUserId', 'referenceHash', 'reference', 'operation', 'requestedDeltaUnits', 'createdAt'], 'crypto_idempotency');

  for (const u of users) {
    if (u._id !== u.externalUserId) {
      throw new Error(`crypto_users: _id ${u._id} !== externalUserId ${u.externalUserId}`);
    }
  }
  for (const e of events) {
    if (e._id !== e.id) throw new Error(`crypto_events: _id ${e._id} !== id ${e.id}`);
  }

  const sql = ['-- generated by migration/build-seed.mjs; do not edit'];

  sql.push(
    ...insert(
      'crypto_users',
      ['external_user_id', 'balance_units', 'last_grant_period', 'created_at', 'updated_at'],
      users.map((u) => ({
        external_user_id: u.externalUserId,
        balance_units: u.balanceUnits,
        last_grant_period: u.lastGrantPeriod ?? null,
        created_at: u.createdAt,
        updated_at: u.updatedAt,
      })),
    ),
  );

  sql.push(
    ...insert(
      'crypto_events',
      ['id', 'host', 'title', 'starts_at', 'stake_units', 'multiplier_bps', 'status', 'created_at', 'revision', 'updated_at'],
      events.map((e) => ({
        id: e.id,
        host: e.host,
        title: e.title,
        starts_at: e.startsAt ?? null,
        stake_units: e.stakeUnits,
        multiplier_bps: e.multiplierBps,
        status: e.status,
        created_at: e.createdAt,
        revision: e.revision,
        updated_at: e.updatedAt,
      })),
    ),
  );
  for (const e of events) {
    sql.push(
      ...insert(
        'crypto_event_rsvps',
        ['event_id', 'user_id', 'position', 'staked_units', 'status', 'payout_units'],
        (e.rsvps ?? []).map((r, position) => ({
          event_id: e.id, user_id: r.userId, position,
          staked_units: r.stakedUnits, status: r.status, payout_units: r.payoutUnits,
        })),
      ),
    );
  }

  sql.push(
    ...insert(
      'crypto_withdrawals',
      ['id', 'external_user_id', 'transfer_id', 'amount_units', 'dest_chain_type', 'dest_chain_id',
        'dest_token_address', 'dest_recipient_address', 'status', 'refunded', 'created_at', 'updated_at'],
      withdrawals.map((w) => ({
        id: w.id,
        external_user_id: w.externalUserId,
        transfer_id: w.transferId ?? null,
        amount_units: w.amountUnits,
        dest_chain_type: w.destination.chain_type,
        dest_chain_id: w.destination.chain_id,
        dest_token_address: w.destination.token_address,
        dest_recipient_address: w.destination.recipient_address,
        status: w.status,
        refunded: w.refunded ? 1 : 0,
        created_at: w.createdAt,
        updated_at: w.updatedAt,
      })),
    ),
  );

  sql.push(
    ...insert(
      'crypto_idempotency',
      ['id', 'external_user_id', 'reference_hash', 'reference', 'operation', 'requested_delta_units', 'created_at'],
      idempotency.map((r) => ({
        id: r._id,
        external_user_id: r.externalUserId,
        reference_hash: r.referenceHash,
        reference: r.reference,
        operation: r.operation ?? null,
        requested_delta_units: r.requestedDeltaUnits ?? null,
        created_at: r.createdAt,
      })),
    ),
  );

  return {
    sql,
    counts: {
      crypto_users: users.length,
      crypto_events: events.length,
      crypto_withdrawals: withdrawals.length,
      crypto_idempotency: idempotency.length,
    },
  };
}

mkdirSync(OUT_DIR, { recursive: true });
const app = buildApp();
const custody = buildCustody();
writeFileSync(join(OUT_DIR, 'seed-app.sql'), app.sql.join('\n') + '\n');
writeFileSync(join(OUT_DIR, 'seed-custody.sql'), custody.sql.join('\n') + '\n');

const total =
  Object.values(app.counts).reduce((a, b) => a + b, 0) +
  Object.values(custody.counts).reduce((a, b) => a + b, 0);
console.log('app     ', app.counts, `${app.sql.length - 2} statements`);
console.log('custody ', custody.counts, `${custody.sql.length - 1} statements`);
console.log('documents total:', total);
